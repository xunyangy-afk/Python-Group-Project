"""
Data cleaning for the TheFinAI/Herculean dataset (Peter-work).
Implements the rules and decisions in plan.md.

Input : data/raw/{prices,news,filings}.parquet   (download from Hugging Face)
Output: data/clean/{prices,news,filings}_clean.parquet
        outputs/validation_report.md
Run   : python3 clean_peter.py
"""
from pathlib import Path
import re
import pandas as pd

RAW = Path("data/raw")
CLEAN = Path("data/clean")
OUT = Path("outputs")
CLEAN.mkdir(parents=True, exist_ok=True)
OUT.mkdir(exist_ok=True)

LARGE_MOVE = 0.12           # D5: flag only, never drop
SHORT_TEXT = 200            # D1: news shorter than this is a fragment
PLACEHOLDER_MAX_LEN = 1000  # D1: placeholder phrasing only counts in short texts (refinement 1)
RISK_REFERENCE_ONLY = 1000  # D4: 10-Q risk section that only points to the 10-K

PLACEHOLDER_PATTERN = (
    r"no substantive|cannot be (?:identified|constructed)|no basis to summarize"
    r"|I can.t provide|could not be retrieved|no (?:actual )?[A-Z]{3,5}[- ]related"
    r"|no [A-Z]{3,5} (?:content|coverage|news)|data-availability limitation"
    r"|does not contain any actual"
)
MONTHS = ("January|February|March|April|May|June|July|August|September|October|November|December"
          "|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec")
ISO_DATE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
TEXT_DATE = re.compile(r"\b(" + MONTHS + r")\.? (\d{1,2}),? (20\d\d)\b")


def latest_date_mentioned(text):
    """Latest explicit calendar date written in the text (ISO or 'Month D, YYYY')."""
    found = [pd.to_datetime(d, errors="coerce") for d in ISO_DATE.findall(text)]
    found += [pd.to_datetime(f"{m} {d} {y}", errors="coerce") for m, d, y in TEXT_DATE.findall(text)]
    found = [d for d in found if pd.notna(d)]
    return max(found) if found else pd.NaT

report = []


def log(text=""):
    print(text)
    report.append(text)


def profile(df, name):
    """Small summary used for before/after comparison."""
    return {
        "table": name,
        "rows": len(df),
        "missing": int(df.isna().sum().sum()),
        "dup_id": int(df["id"].duplicated().sum()),
        "dup_symbol_date": int(df.duplicated(["symbol", "date"]).sum()),
        "symbols": df["symbol"].nunique(),
    }


def common_clean(df):
    """Rules shared by all three tables: id, symbol, date."""
    df = df.copy()
    df["id"] = df["id"].astype("int64")
    df["symbol"] = df["symbol"].str.strip().str.upper().astype("category")
    df["date"] = pd.to_datetime(df["date"])
    return df.sort_values(["symbol", "date"]).reset_index(drop=True)


# ---------------------------------------------------------------- load
prices_raw = pd.read_parquet(RAW / "prices.parquet")
news_raw = pd.read_parquet(RAW / "news.parquet")
filings_raw = pd.read_parquet(RAW / "filings.parquet")
before = [profile(prices_raw, "prices"), profile(news_raw, "news"), profile(filings_raw, "filings")]

log("# Validation Report (Peter-work)")
log()
log("Generated by `clean_peter.py`. Rules and decisions come from `plan.md`.")
log()

# ---------------------------------------------------------------- prices
log("## Step 1: prices")
prices = common_clean(prices_raw)
prices["daily_return"] = prices.groupby("symbol", observed=True)["adj_close"].pct_change()
prices["flag_large_move"] = prices["daily_return"].abs() > LARGE_MOVE
log(f"- Converted date to datetime64, symbol to category. Rows {len(prices_raw)} -> {len(prices)}.")
log(f"- Added daily_return from adj_close (D6). NaN by design on first day of each symbol: "
    f"{int(prices['daily_return'].isna().sum())} rows.")
log(f"- flag_large_move (|return| > {LARGE_MOVE:.0%}, D5): {int(prices['flag_large_move'].sum())} rows, kept.")
log()

# ---------------------------------------------------------------- news
log("## Step 2: news")
news = common_clean(news_raw)
changed_ws = int((news["highlights"] != news["highlights"].str.strip()).sum())
news["highlights"] = news["highlights"].str.strip()
news["text_len"] = news["highlights"].str.len()
# Refinement 1: the first run flagged 20 rows, but 12 were long, substantive summaries that only
# said one of several articles had "no substantive content". A row is a placeholder only if the
# phrasing appears in a short text, or the text is a fragment.
phrase_hit = news["highlights"].str.contains(PLACEHOLDER_PATTERN, case=False, regex=True)
news["flag_placeholder"] = (
    (phrase_hit & (news["text_len"] < PLACEHOLDER_MAX_LEN))
    | (news["text_len"] < SHORT_TEXT)
)
# Refinement 2: a keyword search ("dated after", "post-2025...") matched 33 rows, but almost all were
# disclaimers saying future information had been EXCLUDED. Instead, extract explicit dates from the
# text and flag rows that mention a date later than the row's own date.
news["latest_date_mentioned"] = news["highlights"].map(latest_date_mentioned)
news["flag_lookahead"] = news["latest_date_mentioned"] > news["date"]

trading_days = pd.DataFrame({"next_trading_date": sorted(prices["date"].unique())})
news["is_trading_day"] = news["date"].isin(trading_days["next_trading_date"])
aligned = pd.merge_asof(
    news[["date"]].reset_index().sort_values("date"),
    trading_days.assign(key=trading_days["next_trading_date"]).rename(columns={"key": "date"}),
    on="date",
    direction="forward",
).set_index("index").sort_index()
news["next_trading_date"] = aligned["next_trading_date"]

log(f"- Stripped whitespace on {changed_ws} rows; wording untouched (D3).")
log(f"- Placeholder phrasing found in {int(phrase_hit.sum())} rows; only short ones count (refinement 1).")
log(f"- flag_placeholder (D1): {int(news['flag_placeholder'].sum())} rows, kept.")
log(f"- flag_lookahead (D3): {int(news['flag_lookahead'].sum())} row(s) mention an explicit later date, kept (refinement 2).")
log(f"- Non-trading-day rows (D2): {int((~news['is_trading_day']).sum())}, kept; "
    f"mapped to next_trading_date (missing after mapping: {int(news['next_trading_date'].isna().sum())}).")
log()

# ---------------------------------------------------------------- filings
log("## Step 3: filings")
filings = common_clean(filings_raw)
for col in ["mda_content", "risk_content"]:
    n = int((filings[col] != filings[col].str.strip()).sum())
    filings[col] = filings[col].str.strip()
    log(f"- Stripped leading/trailing whitespace in {col}: {n} rows.")
filings["document_type"] = filings["document_type"].str.strip().astype("category")
bad_types = set(filings["document_type"].unique()) - {"10-K", "10-Q"}
filings["mda_len"] = filings["mda_content"].str.len()
filings["risk_len"] = filings["risk_content"].str.len()
prev_risk = filings.groupby("symbol", observed=True)["risk_content"].shift()
filings["flag_risk_repeat"] = filings["risk_content"] == prev_risk
filings["flag_risk_reference_only"] = filings["risk_len"] < RISK_REFERENCE_ONLY
log(f"- document_type values outside {{10-K, 10-Q}}: {sorted(bad_types) or 'none'}.")
log(f"- flag_risk_repeat (D4): {int(filings['flag_risk_repeat'].sum())} rows, kept.")
log(f"- flag_risk_reference_only (D4): {int(filings['flag_risk_reference_only'].sum())} rows, kept.")
log()

# ---------------------------------------------------------------- save
prices.to_parquet(CLEAN / "prices_clean.parquet", index=False)
news.to_parquet(CLEAN / "news_clean.parquet", index=False)
filings.to_parquet(CLEAN / "filings_clean.parquet", index=False)

# ---------------------------------------------------------------- validation
after = [profile(prices, "prices"), profile(news, "news"), profile(filings, "filings")]
log("## Validation 1: rows, missing values, duplicates (before -> after)")
log()
log("| Table | Rows | Missing | Dup id | Dup symbol+date | Symbols |")
log("|---|---|---|---|---|---|")
for b, a in zip(before, after):
    log(f"| {b['table']} | {b['rows']} -> {a['rows']} | {b['missing']} -> {a['missing']} | "
        f"{b['dup_id']} -> {a['dup_id']} | {b['dup_symbol_date']} -> {a['dup_symbol_date']} | "
        f"{b['symbols']} -> {a['symbols']} |")
log()
log("The 8 new missing values in prices are the first-day daily_return of each symbol (expected). "
    "No original column gained or lost missing values.")
log()

log("## Validation 2: categorical columns")
log()
log(f"- symbol: {', '.join(prices['symbol'].cat.categories)}")
log(f"- rows per symbol, prices: {prices['symbol'].value_counts().sort_index().to_dict()}")
log(f"- rows per symbol, news: {news['symbol'].value_counts().sort_index().to_dict()}")
log(f"- rows per symbol, filings: {filings['symbol'].value_counts().sort_index().to_dict()}")
log(f"- document_type: {filings['document_type'].value_counts().to_dict()}")
log()

log("## Validation 3: numeric ranges")
log()
num = prices[["open", "high", "low", "close", "adj_close", "volume", "daily_return"]].describe().T
log(num[["min", "50%", "max"]].round(4).to_markdown())
log()
ohlc_bad = int(((prices["high"] < prices[["open", "close", "low"]].max(axis=1))
                | (prices["low"] > prices[["open", "close", "high"]].min(axis=1))).sum())
log(f"- OHLC logic violations: {ohlc_bad}")
log(f"- news text_len min / median / max: {news['text_len'].min()} / {int(news['text_len'].median())} / {news['text_len'].max()}")
log(f"- filings risk_len min / median / max: {filings['risk_len'].min()} / {int(filings['risk_len'].median())} / {filings['risk_len'].max()}")
log()

log("## Validation 4: flag counts by symbol")
log()
flags = pd.concat([
    prices.groupby("symbol", observed=True)["flag_large_move"].sum(),
    news.groupby("symbol", observed=True)[["flag_placeholder", "flag_lookahead"]].sum(),
    news.groupby("symbol", observed=True)["is_trading_day"].apply(lambda s: int((~s).sum())).rename("non_trading_news"),
    filings.groupby("symbol", observed=True)[["flag_risk_repeat", "flag_risk_reference_only"]].sum(),
], axis=1).astype(int)
flags.loc["TOTAL"] = flags.sum()
log(flags.to_markdown())
log()

log("## Validation 5: example rows")
log()
log("Large moves (kept, flagged):")
log()
log(prices.loc[prices["flag_large_move"], ["symbol", "date", "close", "daily_return"]]
    .assign(date=lambda d: d["date"].dt.date, daily_return=lambda d: d["daily_return"].round(4))
    .to_markdown(index=False))
log()
log("Placeholder news (all, text truncated):")
log()
log(news.loc[news["flag_placeholder"], ["symbol", "date", "text_len", "highlights"]]
    .assign(date=lambda d: d["date"].dt.date,
            highlights=lambda d: d["highlights"].str.replace("\n", " ").str[:90] + "...")
    .to_markdown(index=False))
log()
log("Look-ahead news (all):")
log()
log(news.loc[news["flag_lookahead"], ["symbol", "date", "latest_date_mentioned"]]
    .assign(date=lambda d: d["date"].dt.date, latest_date_mentioned=lambda d: d["latest_date_mentioned"].dt.date)
    .to_markdown(index=False))
log()
log("Weekend news mapped to next trading day (first 3):")
log()
log(news.loc[~news["is_trading_day"], ["symbol", "date", "next_trading_date"]].head(3)
    .assign(date=lambda d: d["date"].dt.date, next_trading_date=lambda d: d["next_trading_date"].dt.date)
    .to_markdown(index=False))
log()
log("Filings before vs after (first 3 characters of mda_content):")
log()
log(f"- before: {[filings_raw['mda_content'].iloc[i][:3] for i in range(3)]}")
log(f"- after : {[filings['mda_content'].iloc[i][:3] for i in range(3)]}")
log()

log("## Refinements made after the first validation run")
log()
log("1. **Placeholder news.** The first rule flagged 20 rows. Reading them showed 12 were long, real "
    "summaries that only said one of several articles was empty. The rule now requires the placeholder "
    "phrasing in a short text (< 1,000 characters) or a fragment (< 200 characters). Result: 8 rows, all "
    "confirmed by reading.")
log("2. **Look-ahead news.** A keyword search matched 33 rows, but nearly all were disclaimers stating "
    "that future information had been excluded, the opposite of a leak. The rule now compares explicit "
    "dates written in the text with the row date. Result: 1 row (ADBE 2025-02-15 mentions the "
    "2025-02-25 Photoshop for iPhone launch), a real leak.")
log()
log("## Conclusion: does the cleaned data still represent reality?")
log()
log("Yes. No rows were dropped and no original values or wording were changed beyond whitespace, so every "
    "price, news summary, and filing is still what the benchmark agents actually received. Prices pass all "
    "logic checks, and the 9 large moves line up with known events (2025-04-09 tariff pause rally, NVDA "
    "DeepSeek drop on 2025-01-27). The quality problems are now visible through flags instead of hidden: "
    "8 empty news rows, 1 look-ahead leak, 1,232 non-trading-day news rows aligned to the next session, "
    "and 16 filings whose risk section is repeated or only refers to the 10-K. Anyone analysing agent "
    "report quality should filter or control for these flags rather than treat all rows as equal.")
log()

(OUT / "validation_report.md").write_text("\n".join(report) + "\n", encoding="utf-8")
print("\nSaved data/clean/*.parquet and outputs/validation_report.md")
